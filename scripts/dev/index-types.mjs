#!/usr/bin/env node
/**
 * Supabase Types Indexer & Modularizer
 *
 * Divide o monolito `src/integrations/supabase/types.ts` em módulos limpos
 * sob `src/integrations/supabase/types/`:
 *   - database.ts: Contrato Supabase SSOT (Database, Json, Tables, Enums, Constants)
 *   - tables.ts: Tipos ergonômicos por tabela (TableRow, PatientRow, SessionRow, etc.)
 *   - enums.ts: Tipos ergonômicos de enums (SubscriptionPlan, OperationalRoleType, etc.)
 *   - functions.ts: Tipos auxiliares de RPCs (FunctionArgs, FunctionReturns, etc.)
 *   - index.ts: Barrel completo re-exportando os submódulos
 *
 * Converte `src/integrations/supabase/types.ts` em um barrel leve (< 35 linhas)
 * mantendo 100% de compatibilidade retroativa.
 */

import fs from 'fs';
import path from 'path';

const ROOT = process.cwd();
const TYPES_FILE = path.join(ROOT, 'src/integrations/supabase/types.ts');
const TYPES_DIR = path.join(ROOT, 'src/integrations/supabase/types');
const DATABASE_FILE = path.join(TYPES_DIR, 'database.ts');
const TABLES_FILE = path.join(TYPES_DIR, 'tables.ts');
const ENUMS_FILE = path.join(TYPES_DIR, 'enums.ts');
const FUNCTIONS_FILE = path.join(TYPES_DIR, 'functions.ts');
const INDEX_FILE = path.join(TYPES_DIR, 'index.ts');
const BASELINE_PATH = path.join(ROOT, 'scripts/dev/monolith-baseline.json');

function toPascal(str) {
  return str
    .split('_')
    .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
    .join('');
}

function singularize(str) {
  if (str.endsWith('ies')) return str.slice(0, -3) + 'y';
  if (
    str.endsWith('eases') ||
    str.endsWith('ases') ||
    str.endsWith('oses') ||
    str.endsWith('uses')
  ) {
    return str.slice(0, -1);
  }
  if (str.endsWith('sses')) return str.slice(0, -2);
  if (str.endsWith('ses')) return str.slice(0, -1);
  if (
    str.endsWith('s') &&
    !str.endsWith('ss') &&
    !str.endsWith('is') &&
    !str.endsWith('us')
  ) {
    return str.slice(0, -1);
  }
  return str;
}

function getDatabaseContent() {
  if (fs.existsSync(TYPES_FILE)) {
    const content = fs.readFileSync(TYPES_FILE, 'utf8');
    if (content.includes('export type Database = {')) {
      return content;
    }
  }

  if (fs.existsSync(DATABASE_FILE)) {
    return fs.readFileSync(DATABASE_FILE, 'utf8');
  }

  throw new Error('Não foi possível encontrar a definição original de Database');
}

function extractSectionKeys(content, startMarker, endMarker) {
  const pubIdx = content.indexOf('  public: {\n');
  if (pubIdx === -1) return [];

  const sIdx = content.indexOf(`    ${startMarker}: {\n`, pubIdx);
  if (sIdx === -1) return [];

  const eIdx = content.indexOf(`    ${endMarker}: {\n`, sIdx);
  if (eIdx === -1) return [];

  const block = content.slice(sIdx, eIdx);
  return [...block.matchAll(/^ {6}([a-zA-Z0-9_]+):/gm)].map((m) => m[1]);
}

function generateTablesFile(tableKeys) {
  const lines = [
    '// This file is auto-generated by scripts/dev/index-types.mjs. Do not edit directly.',
    'import type { Database } from "./database";',
    '',
    'export type PublicTables = Database["public"]["Tables"];',
    'export type TableName = keyof PublicTables;',
    '',
    'export type TableRow<T extends TableName> = PublicTables[T]["Row"];',
    'export type TableInsert<T extends TableName> = PublicTables[T]["Insert"];',
    'export type TableUpdate<T extends TableName> = PublicTables[T]["Update"];',
    'export type TableRelationships<T extends TableName> = PublicTables[T] extends {',
    '  Relationships: infer R;',
    '}',
    '  ? R',
    '  : unknown[];',
    '',
    'export type PublicViews = Database["public"]["Views"];',
    'export type ViewName = keyof PublicViews;',
    'export type ViewRow<T extends ViewName> = PublicViews[T] extends { Row: infer R }',
    '  ? R',
    '  : never;',
    '',
    '// --- Ergonomic table-specific shortcuts ---',
  ];

  const exported = new Set();

  for (const table of tableKeys) {
    const sing = toPascal(singularize(table));
    const plur = toPascal(table);

    const aliases = [sing];
    if (plur !== sing) {
      aliases.push(plur);
    }

    for (const name of aliases) {
      if (!exported.has(name)) {
        exported.add(name);
        lines.push(`export type ${name}Row = TableRow<"${table}">;`);
        lines.push(`export type ${name}Insert = TableInsert<"${table}">;`);
        lines.push(`export type ${name}Update = TableUpdate<"${table}">;`);
      }
    }
  }

  lines.push('');
  return lines.join('\n');
}

function generateEnumsFile(enumKeys) {
  const lines = [
    '// This file is auto-generated by scripts/dev/index-types.mjs. Do not edit directly.',
    'import type { Database } from "./database";',
    '',
    'export type EnumsMap = Database["public"]["Enums"];',
    'export type EnumType<T extends keyof EnumsMap> = EnumsMap[T];',
    '',
    '// --- Ergonomic enum-specific shortcuts ---',
  ];

  const exported = new Set();

  for (const enumKey of enumKeys) {
    const pascal = toPascal(enumKey);
    if (!exported.has(pascal)) {
      exported.add(pascal);
      lines.push(`export type ${pascal} = EnumType<"${enumKey}">;`);
    }
  }

  lines.push('');
  return lines.join('\n');
}

function generateFunctionsFile(funcKeys) {
  const lines = [
    '// This file is auto-generated by scripts/dev/index-types.mjs. Do not edit directly.',
    'import type { Database } from "./database";',
    '',
    'export type PublicFunctions = Database["public"]["Functions"];',
    'export type FunctionName = keyof PublicFunctions;',
    '',
    'export type FunctionArgs<T extends FunctionName> = PublicFunctions[T]["Args"];',
    'export type FunctionReturns<T extends FunctionName> = PublicFunctions[T]["Returns"];',
    '',
    'export type RpcArgs<T extends FunctionName> = FunctionArgs<T>;',
    'export type RpcReturn<T extends FunctionName> = FunctionReturns<T>;',
    '',
    '// --- Ergonomic RPC-specific shortcuts ---',
  ];

  const exported = new Set();

  for (const funcKey of funcKeys) {
    const pascal = toPascal(funcKey);
    if (!exported.has(pascal)) {
      exported.add(pascal);
      lines.push(`export type ${pascal}Args = FunctionArgs<"${funcKey}">;`);
      lines.push(`export type ${pascal}Returns = FunctionReturns<"${funcKey}">;`);
    }
  }

  lines.push('');
  return lines.join('\n');
}

function generateIndexFile() {
  return [
    '// This file is auto-generated by scripts/dev/index-types.mjs. Do not edit directly.',
    'export * from "./database";',
    'export * from "./tables";',
    'export * from "./enums";',
    'export * from "./functions";',
    '',
  ].join('\n');
}

function generateTypesBarrel() {
  return [
    '/**',
    ' * Supabase Types Modularized Barrel',
    ' *',
    ' * Re-exporta todos os contratos e tipos modularizados de ./types/',
    ' * Preserva compatibilidade total com imports legados.',
    ' */',
    '',
    'export type {',
    '  Json,',
    '  Database,',
    '  Tables,',
    '  TablesInsert,',
    '  TablesUpdate,',
    '  Enums,',
    '  CompositeTypes,',
    '} from "./types/database";',
    '',
    'export { Constants } from "./types/database";',
    '',
    'export * from "./types/tables";',
    'export * from "./types/enums";',
    'export * from "./types/functions";',
    '',
  ].join('\n');
}

function updateMonolithBaseline(barrelLines) {
  if (!fs.existsSync(BASELINE_PATH)) return;
  try {
    const raw = fs.readFileSync(BASELINE_PATH, 'utf8');
    const baseline = JSON.parse(raw);
    const relKey = 'integrations/supabase/types.ts';
    if (baseline[relKey]) {
      baseline[relKey] = Math.max(barrelLines + 10, 35);
      fs.writeFileSync(BASELINE_PATH, JSON.stringify(baseline, null, 2) + '\n', 'utf8');
    }
  } catch (err) {
    console.warn('Aviso: Não foi possível atualizar monolith-baseline.json:', err.message);
  }
}

function main() {
  console.log('⚡ Indexando e modularizando tipos Supabase...');

  fs.mkdirSync(TYPES_DIR, { recursive: true });

  const rawDatabaseContent = getDatabaseContent();

  // 1. Salva database.ts com o schema integral
  fs.writeFileSync(DATABASE_FILE, rawDatabaseContent, 'utf8');

  // 2. Extrai seções
  const tables = extractSectionKeys(rawDatabaseContent, 'Tables', 'Views');
  const functions = extractSectionKeys(rawDatabaseContent, 'Functions', 'Enums');
  const enums = extractSectionKeys(rawDatabaseContent, 'Enums', 'CompositeTypes');

  // 3. Gera submódulos
  const tablesContent = generateTablesFile(tables);
  fs.writeFileSync(TABLES_FILE, tablesContent, 'utf8');

  const enumsContent = generateEnumsFile(enums);
  fs.writeFileSync(ENUMS_FILE, enumsContent, 'utf8');

  const functionsContent = generateFunctionsFile(functions);
  fs.writeFileSync(FUNCTIONS_FILE, functionsContent, 'utf8');

  const indexContent = generateIndexFile();
  fs.writeFileSync(INDEX_FILE, indexContent, 'utf8');

  // 4. Refatora types.ts para ser o barrel leve
  const barrelContent = generateTypesBarrel();
  fs.writeFileSync(TYPES_FILE, barrelContent, 'utf8');

  const barrelLines = barrelContent.split('\n').length;
  updateMonolithBaseline(barrelLines);

  console.log('✅ Modularização de tipos concluída com sucesso!');
  console.log(`  - src/integrations/supabase/types/database.ts: ${rawDatabaseContent.split('\n').length} linhas`);
  console.log(`  - src/integrations/supabase/types/tables.ts: ${tablesContent.split('\n').length} linhas (${tables.length} tabelas mapeadas)`);
  console.log(`  - src/integrations/supabase/types/enums.ts: ${enumsContent.split('\n').length} linhas (${enums.length} enums mapeados)`);
  console.log(`  - src/integrations/supabase/types/functions.ts: ${functionsContent.split('\n').length} linhas (${functions.length} RPCs mapeadas)`);
  console.log(`  - src/integrations/supabase/types/index.ts: ${indexContent.split('\n').length} linhas`);
  console.log(`  - src/integrations/supabase/types.ts: ${barrelLines} linhas (barrel leve)`);
}

main();
